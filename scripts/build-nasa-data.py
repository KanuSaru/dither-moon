"""Turn NASA's CGI Moon Kit maps into src/nasa-data.js.

    python3 scripts/build-nasa-data.py lroc_color_poles_2k.jpg [ldem_3_8bit.jpg]

Both maps are equirectangular with longitude 0 (the side facing Earth) in the
middle. The color map becomes grayscale albedo, contrast-stretched so the seas
read clearly once dithered; the elevation map drives crater relief.
Needs Pillow (pip install pillow).
"""

import base64
import io
import sys
from pathlib import Path

from PIL import Image, ImageFilter, ImageOps

# The moon is drawn about 90–150 pixels across, so the visible half of the map
# needs ~250 pixels: more only adds bytes and shimmer. Elevation is coarser on
# purpose, since relief comes from its slope and fine slopes turn into noise.
ALBEDO_SIZE = (512, 256)
ELEVATION_SIZE = (360, 180)
QUALITY = 80
OUT = Path(__file__).resolve().parent.parent / "src" / "nasa-data.js"


def percentile(img, p):
    hist = img.histogram()
    target = sum(hist) * p
    seen = 0
    for value, count in enumerate(hist):
        seen += count
        if seen >= target:
            return value
    return 255


def albedo(path):
    """Two-tone on purpose: in 1 bit, highlands read best solid and seas as an even dot pattern.

    Measured on the LROC map (grayscale): seas sit around 125-136, highlands around 200.
    A light blur first removes the speckle of small craters and rays, which only
    turns into noise at the size the moon is drawn.
    """
    img = Image.open(path).convert("L").resize(ALBEDO_SIZE, Image.LANCZOS)
    img = img.filter(ImageFilter.GaussianBlur(1.1))
    dark, light = percentile(img, 0.06), percentile(img, 0.55)  # ~seas, ~typical highland

    def curve(v):
        t = min(1.0, max(0.0, (v - dark) / max(1, light - dark)))
        t = t * t * (3 - 2 * t)  # smoothstep
        return round(255 * (0.30 + 0.70 * t))

    return img.point([curve(v) for v in range(256)])


def elevation(path):
    img = Image.open(path).convert("L").resize(ELEVATION_SIZE, Image.LANCZOS)
    img = img.filter(ImageFilter.GaussianBlur(0.8))
    return ImageOps.autocontrast(img, cutoff=0.2)


def data_uri(img):
    buf = io.BytesIO()
    img.save(buf, "JPEG", quality=QUALITY, optimize=True, progressive=False)
    return "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode()


def entry(img):
    if img is None:
        return "null"
    return '{ width: %d, height: %d, src: "%s" }' % (img.width, img.height, data_uri(img))


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    a = albedo(sys.argv[1])
    e = elevation(sys.argv[2]) if len(sys.argv) > 2 else None
    OUT.write_text(
        "// Generated by scripts/build-nasa-data.py from NASA's CGI Moon Kit\n"
        "// (Scientific Visualization Studio; LRO color mosaic, LOLA elevation). Public domain.\n"
        f"export const ALBEDO = {entry(a)};\n"
        f"export const ELEVATION = {entry(e)};\n"
    )
    print(f"wrote {OUT} ({OUT.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
